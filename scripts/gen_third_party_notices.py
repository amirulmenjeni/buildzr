"""Write ``THIRD_PARTY_NOTICES.txt``: the licences and copyright notices of what buildzr ships from others.

Usage (from the repository root, after ``npm ci`` in ``viewer/``)::

    python scripts/gen_third_party_notices.py            # rewrite THIRD_PARTY_NOTICES.txt
    python scripts/gen_third_party_notices.py --check    # exit 1 if the file is out of date

Covers what a wheel or the viewer bundle carries:

* the npm packages the viewer bundle links in: the production dependencies of ``viewer/package.json``
  as ``viewer/package-lock.json`` resolves them, minus the type-only ones (``@types/*``, ``csstype``), which
  produce no code. Their licence texts are read from ``viewer/node_modules``, so the file always quotes what
  the installed package says;
* Inter (``@fontsource/inter``, the two woff2 files of ``viewer/src/fonts/`` and the advance widths of
  ``buildzr/site/fonts/font_metrics.json``);
* elkjs, the vendored ``buildzr/site/layout/vendor/elk.bundled.js``.

The Java libraries of the optional PlantUML export are downloaded on first use and are not distributed.
Deterministic: the same sources give the same bytes. Stdlib only.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
VIEWER = ROOT / "viewer"
OUT = ROOT / "THIRD_PARTY_NOTICES.txt"
TYPE_ONLY = re.compile(r"^(@types/.+|csstype)$")
RULE = "=" * 78

HEADER = """\
buildzr third-party notices
{rule}

buildzr is released under the MIT License (LICENSE.md). Its viewer, the part of the
package that runs in a browser, and its layout stage include the third-party
software and fonts listed below. This file reproduces their copyright notices and
licence texts, as those licences require. It is generated by
scripts/gen_third_party_notices.py; do not edit it by hand.

Everything here is distributed with the package. The viewer loads all of it from the
same origin and never contacts a font or script host at run time. The Java libraries
of the optional PlantUML export (structurizr-export, structurizr-core,
commons-logging and plantuml) are not part of the package: they are downloaded from
Maven Central on first use and keep their own licences.
""".format(rule=RULE)


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n")


def bundled_packages() -> list[tuple[str, str, str]]:
    """``(name, version, licence id)`` of the production npm packages of the viewer bundle, sorted."""
    lock = json.loads((VIEWER / "package-lock.json").read_text(encoding="utf-8"))["packages"]
    found = []
    for key, pkg in lock.items():
        if not key or pkg.get("dev") or pkg.get("peer") and pkg.get("optional"):
            continue
        name = key.split("node_modules/")[-1]
        if not TYPE_ONLY.match(name):
            found.append((name, pkg["version"], pkg["license"]))
    return sorted(found)


def package_info(name: str) -> dict[str, Any]:
    return json.loads((VIEWER / "node_modules" / name / "package.json").read_text(encoding="utf-8"))


def licence_text(name: str) -> str:
    folder = VIEWER / "node_modules" / name
    (path,) = [p for p in folder.iterdir() if re.match(r"licen[cs]e(\.md|\.txt)?$", p.name, re.I)]
    return read(path)


def source_url(name: str) -> str:
    repo = package_info(name).get("repository", "")
    url = repo.get("url", "") if isinstance(repo, dict) else repo
    if re.fullmatch(r"[\w.-]+/[\w.-]+", url):  # npm shorthand for GitHub
        url = "https://github.com/" + url
    return re.sub(r"^(git\+|git://)", lambda m: "" if m.group(1) == "git+" else "https://", url).removesuffix(".git")


def section(title: str) -> str:
    return f"\n{RULE}\n{title}\n{RULE}\n"


def render() -> str:
    parts = [HEADER]

    parts.append(section("Inter (font)"))
    parts.append(
        "Components: the Inter regular (400) and bold (700) latin subsets in woff2 form, bundled in the\n"
        "viewer as its default font, and the advance widths of ASCII 32-126 that the layout stage\n"
        "measures labels with.\n"
        "Version: @fontsource/inter 5.3.0 (sha256 of the woff2 files in viewer/src/fonts/ matches the\n"
        "files of that package)\n"
        "Licence: SIL Open Font License, Version 1.1\n"
        "Source: https://github.com/rsms/inter, https://fontsource.org/fonts/inter\n\n"
        + read(VIEWER / "src" / "fonts" / "OFL.txt")
        + "\n"
    )

    parts.append(section("elkjs (Eclipse Layout Kernel, JavaScript build)"))
    parts.append(
        "Component: buildzr/site/layout/vendor/elk.bundled.js, unmodified\n"
        "Version: elkjs 0.12.0\n"
        "Licence: Eclipse Public License - v 2.0\n"
        "Source: https://github.com/kieler/elkjs, https://github.com/eclipse/elk\n\n"
        + read(ROOT / "buildzr" / "site" / "layout" / "vendor" / "NOTICE")
        + "\n\n"
        + read(ROOT / "buildzr" / "site" / "layout" / "vendor" / "LICENSE-EPL-2.0.md")
        + "\n"
    )

    # npm packages: one block per distinct licence text, listing every package that carries it.
    groups: dict[str, list[tuple[str, str, str]]] = {}
    for name, version, spdx in bundled_packages():
        groups.setdefault(licence_text(name), []).append((name, version, spdx))
    parts.append(section("npm packages linked into the viewer bundle"))
    for text, members in sorted(groups.items(), key=lambda kv: kv[1][0][0]):
        parts.append("Packages:\n")
        for name, version, spdx in members:
            parts.append(f"  {name} {version}  ({spdx})  {source_url(name)}\n")
        parts.append("\nLicence text, as shipped in each of these packages:\n\n" + text + "\n")
        parts.append("\n" + "-" * 78 + "\n\n")
    out = "".join(parts).rstrip("\n") + "\n"
    return out


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is out of date: run python scripts/gen_third_party_notices.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} is up to date ({hashlib.sha256(text.encode()).hexdigest()[:12]})")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
